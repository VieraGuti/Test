export type EmbedScope=typeof EMBED_CATALOG[number]['id'];
export const EMBED_SCOPES=EMBED_CATALOG.map(x=>x.id);
export const EVENT_PHASES=['event-registration-open','event-registration-closed','event-announcement','event-winner','event-summary'] as const;
export type EventEmbedPhase=typeof EVENT_PHASES[number];
export type EmbedMedia={image:string;thumbnail:string};
export type EventArtwork=EmbedMedia&{mediaByPhase?:Partial<Record<EventEmbedPhase,EmbedMedia>>};
export const EMPTY_MEDIA:EmbedMedia={image:'',thumbnail:''};
export function validMediaUrl(v:unknown):v is string{if(typeof v!=='string'||v.length>1500)return false;if(v==='')return true;try{const u=new URL(v);return u.protocol==='https:'&&!!u.hostname&&!u.username&&!u.password&&!/[\u0000-\u001f\u007f\s]/.test(v);}catch{return false;}}
export function cleanMedia(v:unknown):EmbedMedia{const x=v&&typeof v==='object'?v as Record<string,unknown>:{};return {image:validMediaUrl(x.image)?x.image:'',thumbnail:validMediaUrl(x.thumbnail)?x.thumbnail:''};}
export function isEventScope(scope:EmbedScope){return scope==='events'||EVENT_PHASES.some(p=>p===scope);}
export function inheritedMedia(settings:unknown,scope:EmbedScope):EmbedMedia{const x=settings&&typeof settings==='object'?settings as Record<string,unknown>:{};const parent=isEventScope(scope)&&scope!=='events'?'events':scope.startsWith('kill-')?'kills':'default';return cleanMedia(x[scope]??x[parent]??x.default);}
export function discordMedia(settings:unknown,scope:EmbedScope,event?:Partial<EventArtwork>){const x=settings&&typeof settings==='object'?settings as Record<string,unknown>:{};const selected=inheritedMedia(x,scope);const local=cleanMedia(event);const phase=event?.mediaByPhase?.[scope as EventEmbedPhase];let chosen=selected;if(isEventScope(scope)){if(phase)chosen=cleanMedia(phase);else if(scope!=='events'&&x[scope])chosen=cleanMedia(x[scope]);else chosen={image:local.image||selected.image,thumbnail:local.thumbnail||selected.thumbnail};}return {...(chosen.image?{image:{url:chosen.image}}:{}),...(chosen.thumbnail?{thumbnail:{url:chosen.thumbnail}}:{})};}
export function validatePhaseMedia(value:unknown):boolean{if(value===undefined)return true;if(!value||typeof value!=='object'||Array.isArray(value))return false;return Object.entries(value).every(([key,v])=>EVENT_PHASES.some(p=>p===key)&&!!v&&typeof v==='object'&&!Array.isArray(v)&&Object.keys(v).every(k=>k==='image'||k==='thumbnail')&&validMediaUrl((v as EmbedMedia).image)&&validMediaUrl((v as EmbedMedia).thumbnail));}
